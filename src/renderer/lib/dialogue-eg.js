// put the placeholder in a different position than English does, which is fine —
// the check is that it is used at all, not where.
//
// A note on the mixing: English words are written in Latin script, not
// transliterated into Arabic letters. That is how they are typed in real life,
// and it keeps them readable at bubble size.

