// 'auto' follows the system. Anything unknown falls back to English rather than
// to an empty menu.
export function resolveLanguage(setting, systemLocale = 'en') {
  if (setting && setting !== 'auto' && STRINGS[setting]) return setting;
  const base = String(systemLocale || 'en').toLowerCase().split(/[-_]/)[0];
  return STRINGS[base] ? base : 'en';
}

