export const STRINGS = { en: EN, ar: AR };

// Look up a string, filling {placeholders}. Falls back through the language to
// English to the key itself, so a missing string shows up as something legible
// rather than as an empty menu item.
export function t(lang, key, vars) {
  let s = (STRINGS[lang] && STRINGS[lang][key]) ?? EN[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

// Bound to one language, for call sites that would otherwise thread `lang`
// through every single call.
export const translator = (lang) => (key, vars) => t(lang, key, vars);
